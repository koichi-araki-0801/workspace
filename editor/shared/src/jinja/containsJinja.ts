// =============================================================================
// containsJinja.ts — HTML 断片が Jinja のタグを含むかの判定
// =============================================================================
// 編集タブで挿入したパーツは値入りの地の HTML になり、Jinja の原文は本文に残らない。承認後の
// ペア同期と注記マスタの書き戻しは、カタログの `内容HTML` が Jinja を含むかで扱いを分ける
// (含むものは値ごとに描き直す・マスタへ書き戻さない)。区切りは `lexJinja` と同じものを使う。

import { lexJinja } from './jinjaLex.js';

/**
 * `html` に Jinja のタグ(`{{ }}` `{% %}` `{# #}`)が 1 つでもあれば true。閉じていない開き記号も
 * true に倒す: 呼び出し側はどちらも「Jinja を含む」側を安全側として扱う(描き直しは描画の例外で
 * 手を付けずに残し、書き戻しは対象から外す)。
 */
export function containsJinja(html: string): boolean {
  const r = lexJinja(html);
  return !r.ok || r.tokens.length > 0;
}
