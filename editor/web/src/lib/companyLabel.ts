/** Rep1 に見つからない委託会社・ファンドの表示。 */
export const UNREGISTERED = '（未登録）';

/** 委託会社の表示。作成タブの候補と、ファイル名の略称から引いた表示で共用する。 */
export function formatCompanyLabel(abbr: string, rep1: string): string {
  return `${abbr}（${rep1}）`;
}
